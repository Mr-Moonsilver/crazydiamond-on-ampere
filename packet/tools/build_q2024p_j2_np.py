#!/usr/bin/env python3
"""Compose the exploratory q2024p-j2 night-pack family (lead 12 Nov 2026) from the measured j2 bundle: ONE source commit,
every packet differing only in its launch flags, so np-off is the exact baseline of each lever packet.

This is the ing tool (tools/build_q2024p_j2_ing.py, through it the yr, yrs and host-gap batch tools) reused unchanged in
method: the same sealed q2024p-j2 parent bundle f63cff5d1e19, the same source delta copy (each modified file first proved
byte-identical to the parent bundle's copy), the same observational n3j2_box line, the overlay regenerated by the frozen
generator, the owner runner, frozen CPU tool and queue adapter under the new name. What differs:
  * the queue triple: the settings carry all five flags (FLASH_S5_SMALL_PIECE_BATCH, FLASH_S5_YIELD_REENTRY_SETTLE,
    FLASH_S5_YIELD_NO_APPEND_OWNER, FLASH_S5_YIELD_WINDOW, FLASH_S5_INGRESS_INCREMENTAL) at the variant's values, and with
    ingress on the verify settings FLASH_S5_INGRESS_VERIFY_EVERY=1 FLASH_S5_INGRESS_VERIFY_ASYNC=1 (every splice, off-path);
    the declaration and the draft assert each one. The anchors are the variant's own values (the yr/ing tools anchor on 0);
  * the names: q18a-parity-n3s24q2024p-j2-np-<variant>; the -n2 variants are second transports of off and y12: the same
    flags under their own QNAME (the box keys its outputs by QNAME), never a retry of the same name;
  * the CPU suites: the ing packet's plus test_q2024p_j2_np_reader.
No box command, GPU, VM, deletion or push.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location('build_q2024p_j2_ing', ROOT / 'tools/build_q2024p_j2_ing.py')
ing = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ing)
yr, yrs, hgb = ing.yr, ing.yrs, ing.hgb

PARENT_NAME, PARENT, BASE_COMMIT = hgb.PARENT_NAME, hgb.PARENT, hgb.BASE_COMMIT
_OFF = dict(small_piece_batch='0', yield_reentry_settle='0', no_append_owner='0', yield_window='0',
            ingress_incremental='0', verify_every=None, verify_async=None)
_ING = dict(ingress_incremental='1', verify_every='1', verify_async='1')
VARIANTS = {
    'off': dict(_OFF),
    'off-n2': dict(_OFF),
    'y12': dict(_OFF, no_append_owner='1', yield_window='1'),
    'y12-n2': dict(_OFF, no_append_owner='1', yield_window='1'),
    'ing': dict(_OFF, **_ING),
    'all': dict(_OFF, no_append_owner='1', yield_window='1', **_ING),
    'set': dict(_OFF, yield_reentry_settle='1'),
    'hgb': dict(_OFF, small_piece_batch='1'),
}
VERIFY_EVERY_ENV, VERIFY_ASYNC_ENV = 'FLASH_S5_INGRESS_VERIFY_EVERY', 'FLASH_S5_INGRESS_VERIFY_ASYNC'
BOUND_MODULES = ing.BOUND_MODULES
ENGINE_MOVED = ing.ENGINE_MOVED
NEW_OVERLAY_FILES = ing.NEW_OVERLAY_FILES
SUITES = ing.SUITES + ('test_q2024p_j2_np_reader',)
TOOLS = ing.TOOLS + ('tools/q2024p_j2_np_reader.py', 'tools/build_q2024p_j2_np.py', 'tools/q2024p_j2_np_finish.py')
NP_CONTAINER = "'q2024p-j2-np-frozen-cpu-'"


def name_of(variant):
    assert variant in VARIANTS, variant
    return PARENT_NAME + '-np-' + variant


def queues(variant):
    """The yrs triple (batch and settle at the variant's values) under the new name; then Y1, Y2, ingress (and with
    ingress on the verify settings) after the settle setting, each with its assertion."""
    v = VARIANTS[variant]
    settle_setting = '%s=%s ' % (yrs.YRS_ENV, v['yield_reentry_settle'])
    settle_assert = "assert env.get('%s') == '%s', 'yield re-entry settle setting differs'\n" % (
        yrs.YRS_ENV, v['yield_reentry_settle'])
    pairs = [(yr.Y1_ENV, v['no_append_owner'], 'yield rule Y1 setting differs'),
             (yr.Y2_ENV, v['yield_window'], 'yield rule Y2 setting differs'),
             (ing.ING_ENV, v['ingress_incremental'], 'ingress setting differs')]
    if v['ingress_incremental'] == '1':
        pairs += [(VERIFY_EVERY_ENV, v['verify_every'], 'ingress verify rate differs'),
                  (VERIFY_ASYNC_ENV, v['verify_async'], 'ingress verify mode differs')]
    result = {}
    for rel, text in yrs.queues(variant).items():
        if rel.endswith('_settings.sh'):
            text = hgb.once(text, settle_setting, settle_setting + ''.join('%s=%s ' % (e, x) for e, x, _ in pairs))
        else:
            text = hgb.once(text, settle_assert, settle_assert + ''.join(
                "assert env.get('%s') == '%s', '%s'\n" % (e, x, why) for e, x, why in pairs))
        result[rel] = text
    return result


def bind():
    """Point the ing (and through it the yr, yrs and hgb) helpers at this family's names and inventory."""
    ing.bind()
    yr.VARIANTS = yrs.VARIANTS = VARIANTS
    yr.name_of = yrs.name_of = hgb.name_of = name_of
    yr.SUITES = yrs.SUITES = hgb.SUITES = SUITES
    yr.TOOLS = yrs.TOOLS = TOOLS
    yr.YR_CONTAINER = yrs.YRS_CONTAINER = NP_CONTAINER
    yr.queues = queues
    yrs.bind()
    hgb.NEW_OVERLAY_FILES = NEW_OVERLAY_FILES


def copy_delta(b, commit, bundle):
    copied = ing.copy_delta(b, commit, bundle)
    for name in ('harness/test_q2024p_j2_np_reader.py', 'patches/s5_engine/native_auto_arm.py',
                 'patches/s5_engine/small_piece_batch.py'):
        assert name in copied, name
    return copied


def prepare(commit, variant, out):
    """ing.prepare's steps in its order, with this family's queues, delta check and record."""
    bind()
    b = hgb.helper()
    name = name_of(variant)
    commit = b.git(ROOT, 'rev-parse', commit + '^{commit}').decode().strip()
    assert len(commit) == 40
    assert not out.exists() and not out.is_symlink(), 'fresh output required'
    out.mkdir(parents=True)
    bundle = out / (name + '-bundle-pending')
    shutil.copytree(PARENT, bundle)
    for p in (bundle, *bundle.rglob('*')):
        p.chmod(0o755 if p.is_dir() else 0o644)
    copied = copy_delta(b, commit, bundle)
    box = bundle / 'n3j2_box.py'
    box.write_text(hgb.once(hgb.once(box.read_text(), hgb.BOX_IMPORT, hgb.BOX_IMPORT_NEW), hgb.BOX_ROW, hgb.BOX_ROW_NEW))
    for rel, text in queues(variant).items():
        (bundle / rel).write_text(text)
        subprocess.run(['bash', '-n', str(bundle / rel)], check=True)
    proof = hgb.regenerate(b, bundle, out)
    assert set(NEW_OVERLAY_FILES) <= set(proof['overlay_changed']), 'new overlay files not in the regenerated overlay'
    yrs.frozen_cpu_tool(bundle)
    hgb.queue_adapter(bundle, variant)
    for p in bundle.rglob('*.py'):
        compile(p.read_bytes(), str(p), 'exec')
    manifest = b.manifest(bundle)
    final = out / (name + '-bundle-' + manifest[:12])
    bundle.rename(final)
    runner = out / (name + '-owner-run-' + manifest[:12] + '.py')
    runner.write_text(hgb.runner_text(b, final, manifest, proof, commit, variant))
    compile(runner.read_bytes(), str(runner), 'exec')
    for p in (final, *final.rglob('*')):
        p.chmod(0o555 if p.is_dir() else 0o444)
    runner.chmod(0o444)
    v = VARIANTS[variant]
    record = dict(proof, schema='q2024p-j2-np-build/1', name=name, variant=variant, family='q2024p-j2-np',
                  small_piece_batch=v['small_piece_batch'], yield_reentry_settle=v['yield_reentry_settle'],
                  no_append_owner=v['no_append_owner'], yield_window=v['yield_window'],
                  ingress_incremental=v['ingress_incremental'], ingress_verify_every=v['verify_every'],
                  ingress_verify_async=v['verify_async'], diagnostic='always-on',
                  prefix_counter='always-on in engine arms (log-only)', new_overlay_files=sorted(NEW_OVERLAY_FILES),
                  source_commit=commit, base_commit=BASE_COMMIT,
                  bundle=str(final), manifest=manifest, runner=str(runner), runner_sha256=b.sha(runner),
                  runner_size=runner.stat().st_size, held=True, hardware_qualified=False, exploratory=True,
                  parent_manifest=hgb.PARENT_SHA, parent_runner_sha256=hgb.PARENT_RUNNER_SHA,
                  parent_overlay=hgb.PARENT_OVERLAY, source_changes=copied, cpu_suites=SUITES,
                  hgb_modules=BOUND_MODULES, box_action=False, gpu_action=False)
    b.dump(out / 'build.json', record)
    return record


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source-commit', required=True)
    parser.add_argument('--variant', choices=sorted(VARIANTS), required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.source_commit, args.variant, args.out.resolve())
    print(json.dumps({k: v for k, v in result.items() if k != 'source_changes'}, sort_keys=True))
