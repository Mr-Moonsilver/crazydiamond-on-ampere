#!/usr/bin/env python3
"""lane-o3-fix (from lane-o3-batch): e3_lane_o3_probe's cases in a CPU container on a parent bundle's generated worker/core bytes plus THIS tree's
packaged E3 modules and harness (codex/lane-batch-b's lane_batch_b_stack_cpu.py layout). A source projection, not a frozen box
overlay: no pass here is box evidence. CPU only: runc, no network, no device."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'patches/s5_engine'), str(ROOT / 'harness')]
from native37_robust_selfrun import IMAGE, overlay_mounts  # noqa: E402
from make_s5_overlap import E3_MODULES, package  # noqa: E402
from e3_lane_o3_probe import CASES  # noqa: E402

E3_TARGET = '/usr/local/lib/python3.12/dist-packages/vllm/v1/flash_e3'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--parent', type=Path, required=True, help='a built bundle (its native30_overlay generated bytes)')
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--name', required=True)
    p.add_argument('--cases', nargs='+', choices=CASES, default=list(CASES))
    a = p.parse_args()
    parent, out = a.parent.resolve(), a.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    out.chmod(0o777)
    e3 = out / 'e3'
    e3.mkdir()
    (e3 / '__init__.py').write_text('"""CPU source projection; not a frozen box overlay."""\n')
    sources = {}
    for name in E3_MODULES:
        source = ROOT / 'patches/s5_engine' / (name + '.py')
        dest = e3 / source.name
        dest.write_text(package(source.read_text()))
        compile(dest.read_text(), str(dest), 'exec')
        sources[name] = dict(source_sha256=sha(source), packaged_sha256=sha(dest))
    lines = ['set -u', 'cd /source/harness']
    for case in a.cases:
        lines.append('python3 -B e3_lane_o3_probe.py --case %s --out /out/%s.json > /out/%s.log 2>&1; echo $? > /out/%s.rc'
                     % (case, case, case, case))
    (out / 'inner.sh').write_text('\n'.join(lines) + '\n')
    mounts = {str(s): t for s, t in overlay_mounts(parent / 'native30_overlay').items()}
    mounts = {s: t for s, t in mounts.items() if t != E3_TARGET}
    mounts.update({str(e3): E3_TARGET, str(ROOT / 'harness'): '/source/harness', str(ROOT / 'patches'): '/source/patches',
                   str(ROOT / 'tools'): '/source/tools',
                   str((ROOT / 'reference/vllm-src').resolve()): '/source/reference/vllm-src'})
    c = ['sudo', '-n', 'docker', 'run', '--pull=never', '--name', a.name, '--runtime', 'runc', '--network', 'none',
         '--cpus', '4', '--memory', '6g', '--memory-swap', '6g', '--read-only',
         '--tmpfs', '/tmp:rw,exec,nosuid,nodev,size=1g', '--ulimit', 'core=0',
         '-e', 'VLLM_CACHE_ROOT=/tmp/vllm-cache', '-e', 'NVIDIA_VISIBLE_DEVICES=none', '-e', 'CUDA_VISIBLE_DEVICES=',
         '-e', 'PYTHONDONTWRITEBYTECODE=1', '-e', 'PYTHONPATH=/source/harness:/source/patches/s5_engine']
    for source, target in mounts.items():
        c += ['-v', '%s:%s:ro' % (source, target)]
    c += ['-v', '%s:/out' % out, '--entrypoint', 'bash', IMAGE, '/out/inner.sh']
    started = time.monotonic()
    with (out / 'container.log').open('x') as f:
        rc = subprocess.call(c, stdout=f, stderr=subprocess.STDOUT)
    inspected = json.loads(subprocess.check_output(['sudo', '-n', 'docker', 'inspect', a.name], text=True))[0]['HostConfig']
    no_gpu = (not inspected.get('DeviceRequests') and not inspected.get('Devices') and inspected['NetworkMode'] == 'none'
              and inspected['Runtime'] == 'runc')
    rows = {}
    for case in a.cases:
        path = out / (case + '.json')
        record = json.loads(path.read_text()) if path.exists() else {}
        rows[case] = dict(verdict=record.get('verdict'), violations=record.get('violations'),
                          expect_violation=record.get('expect_violation'), checks=len(record.get('checks') or ()),
                          error=record.get('error') or record.get('error_type'), wall_s=record.get('wall_s'),
                          sha256=sha(path) if path.exists() else None)
    ok = rc == 0 and no_gpu and all(row['verdict'] == 'PASS' for row in rows.values())
    result = dict(schema='lane-o3-src-cpu-result/1', verdict='PASS' if ok else 'FAIL', container_rc=rc, no_gpu_no_network=no_gpu,
                  cases=rows, parent_manifest=sha(parent / 'SHA256SUMS'), image=IMAGE, wall_s=round(time.monotonic() - started, 1),
                  probe_sha256=sha(ROOT / 'harness/e3_lane_o3_probe.py'), sources=sources, command=c,
                  gpu_execution=False, box_evidence=False, source_projection=True)
    (out / 'result.json').write_text(json.dumps(result, indent=2, sort_keys=True) + '\n')
    print(json.dumps(dict(verdict=result['verdict'], cases={k: v['verdict'] for k, v in rows.items()})))
    return 0 if ok else 1


if __name__ == '__main__':
    raise SystemExit(main())
