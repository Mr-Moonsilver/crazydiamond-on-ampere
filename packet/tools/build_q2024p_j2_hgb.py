ROOT = Path(__file__).resolve().parents[1]
PARENT_NAME = 'q18a-parity-n3s24q2024p-j2'
PARENT_BUILD = Path('<hub-dir>/cargo-target/flash-next/q2024p-j2-20261110/build-5')
PARENT = PARENT_BUILD / (PARENT_NAME + '-bundle-f63cff5d1e19')
PARENT_SHA = 'f63cff5d1e19048c2a4c7ffe784f250f9275814ec690579f9a80bc807c678d9f'
PARENT_RUNNER = PARENT_BUILD / (PARENT_NAME + '-owner-run-f63cff5d1e19.py')
PARENT_RUNNER_SHA = 'a379a5e59d64b48e889a5a2ae1ca918474e7acb6e8c459b6ba648242fb0356b8'
PARENT_OVERLAY = '07ebcd44957a398292edf079aa24cf8f6456edb7031a79be5b3300d53a9c64df'
BASE_COMMIT = '06d2beee5a131809a35b05d87eae3430e04ea8a5'
VARIANTS = {'off': '0', 'on': '1'}
HGB_MODULES = ('small_piece_batch', 's5_startup', 'executor_hooks', 'stage_wire', 'decode_probe')
ENGINE_MOVED = {'e3/' + n + '.py' for n in HGB_MODULES}
