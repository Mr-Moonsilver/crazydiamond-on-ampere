# this bundle's frozen environment it fails 16 of its cases against j2's table (per_bulk 8) and leaks into
# test_append_yield; on the source trees it is 7/8 on both the j2 parent and this branch (one pre-existing k2_settle
# failure), run separately as the router smoke.
SUITES = ('test_n3_junction_yield', 'test_n3_shortest_bulk', 'test_n3_yield_quota',
          'test_compose4_request_ids', 'test_append_yield', 'test_coverage_residue', 'test_compose5_declines',
          'test_lane_o3', 'test_native40_unarmed_hold', 'test_n3j2_junction_rule', 'test_n3j2_junction_rule_mutants',
          'test_q2024p_j2', 'test_n3_next_layer_prefetch', 'test_n3_producer_witness', 'test_n3_fused_phases',
          'test_n3_gap_receipts', 'test_n3_indexer_lifetime', 'test_small_piece_batch', 'test_small_piece_batch_box',
          'test_small_piece_batch_reader')
BOX_IMPORT = 'import e3_compose5_box\n'
BOX_IMPORT_NEW = ('import e3_compose5_box\n'
                  'from small_piece_batch_record import persist as persist_small_piece_batch  # host-gap batch (observational)\n')
BOX_ROW = "        row['native_admission'] = reply.get('native_admission')\n    return row\n"
BOX_ROW_NEW = ("        row['native_admission'] = reply.get('native_admission')\n"
               "    # host-gap batch (observational): keep the engine's small_piece_batch block; no key when the flag is 0.\n"
               "    persist_small_piece_batch(row, reply)\n    return row\n")


def name_of(variant):
    assert variant in VARIANTS, variant
    return PARENT_NAME + '-hgb-' + variant


def under(name):
    return name.replace('-', '_')


def helper():
    spec = importlib.util.spec_from_file_location('sealed_j2_build', PARENT / 'tools/build_n3j2.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.verify_manifest(PARENT, PARENT_SHA)
    assert module.sha(PARENT_RUNNER) == PARENT_RUNNER_SHA, 'parent runner pin differs'
    assert module.sha(PARENT / 'native30_overlay/SHA256SUMS') == PARENT_OVERLAY, 'parent overlay pin differs'
    return module


def once(text, old, new):
    assert text.count(old) == 1, (old[:80], text.count(old))
    return text.replace(old, new, 1)


def copy_delta(b, commit, bundle):
    """The reviewed delta: added files and modified files whose parent-bundle copy is the base commit's bytes."""
    rows = b.git(ROOT, 'diff', '--name-status', BASE_COMMIT, commit, '--', 'harness', 'patches/s5_engine').decode().splitlines()
    copied = {}
    for row in rows:
        status, name = row.split('\t')
        assert status in ('A', 'M'), 'deletion/rename outside this packet: ' + row
        path = Path(name)
        target = bundle / (path.relative_to('harness') if path.parts[0] == 'harness'
                           else Path('e3_builder') / path.relative_to('patches/s5_engine'))
        if status == 'M':
            assert target.is_file() and target.read_bytes() == b.git(ROOT, 'show', BASE_COMMIT + ':' + name), \
                'parent bundle copy differs from the base commit: ' + name
        else:
            assert not target.exists(), 'added file already in parent bundle: ' + name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(b.git(ROOT, 'show', commit + ':' + name))
        copied[name] = dict(status=status, bundle=target.relative_to(bundle).as_posix(), sha256=b.sha(target))
    assert 'patches/s5_engine/small_piece_batch.py' in copied and 'patches/s5_engine/native_candidate_review.json' in copied
    for tool in ('tools/q2024p_j2_hgb_reader.py', 'tools/build_q2024p_j2_hgb.py'):
        target = bundle / 'tools' / Path(tool).name
        target.write_bytes(b.git(ROOT, 'show', commit + ':' + tool))
        copied[tool] = dict(status='A', bundle=target.relative_to(bundle).as_posix(), sha256=b.sha(target))
    return copied


def queues(variant):
    """The parent's queue triple under the new name; only the batch setting and its two assertions are added."""
    name, value = name_of(variant), VARIANTS[variant]
    result = {}
    for suffix in ('.draft.sh', '_declare.sh', '_settings.sh'):
        text = (PARENT / 'runs' / (under(PARENT_NAME) + suffix)).read_text()
        text = text.replace(under(PARENT_NAME), under(name)).replace(PARENT_NAME, name)
        if suffix == '_settings.sh':
            text = once(text, 'FLASH_S5_NEXT_LAYER_PREFETCH=1 ',
                        'FLASH_S5_NEXT_LAYER_PREFETCH=1 FLASH_S5_SMALL_PIECE_BATCH=%s ' % value)
        else:
            anchor = "assert env.get('FLASH_S5_NEXT_LAYER_PREFETCH') == '1', 'prefetch differs'\n"
            text = once(text, anchor, anchor + "assert env.get('FLASH_S5_SMALL_PIECE_BATCH') == '%s', "
                                               "'host-gap batch setting differs'\n" % value)
        result['runs/' + under(name) + suffix] = text
    return result


def regenerate(b, bundle, out):
    """build_n3j2.regenerate with this packet's declared inventory: one new runtime file, the host-gap files moved."""
    source = (PARENT / 'tools/build_n3j2.py').read_text()
    source = once(source, "    assert set(old) == set(new), 'unexpected new overlay file inventory'\n",
                  "    assert set(new) == set(old) | NEW_OVERLAY_FILES, 'unexpected new overlay file inventory'\n")
    source = once(source, "    moved = sorted(n for n in old if old[n] != new[n])\n",
                  "    moved = sorted([n for n in old if old[n] != new[n]] + sorted(NEW_OVERLAY_FILES))\n")
    source = once(source, "    engine = {'e3/engine_driver.py','e3/scheduler_hooks.py'}\n", "    engine = ENGINE_MOVED\n")
    module = type(sys)('q2024p_j2_hgb_regenerator')
    module.__file__ = str(PARENT / 'tools/build_n3j2.py')
    exec(compile(source, module.__file__, 'exec'), module.__dict__)
    module.PARENT, module.NEW_OVERLAY_FILES, module.ENGINE_MOVED = PARENT, NEW_OVERLAY_FILES, ENGINE_MOVED
    proof = module.regenerate(bundle, out)
    assert set(proof['overlay_changed']) <= ENGINE_MOVED | METADATA and ENGINE_MOVED <= set(proof['overlay_changed'])
    return proof


def frozen_cpu_tool(bundle):
    """The parent's frozen CPU tool, also binding the host-gap source and mounted generated modules."""
    text = (bundle / 'tools/n3j2_frozen_cpu.py').read_text()
    text = once(text, "    for name, row in modules.items():\n",
                "    import importlib\n"
                "    hgb = {name: {'path':str(Path(importlib.import_module(name).__file__).resolve()),\n"
                "                  'sha256':sha(importlib.import_module(name).__file__)} for name in spec['hgb_source_shas']}\n"
                "    for name, row in hgb.items():\n"
                "        if row['path'] != '/src/patches/s5_engine/'+name+'.py' or row['sha256'] != spec['hgb_source_shas'][name]:\n"
                "            failures.append('source-shadowed:'+name)\n"
                "    mounted = {name: {'path':path,'sha256':sha(path)} for name,path in spec['hgb_generated_paths'].items()}\n"
                "    for name, row in mounted.items():\n"
                "        if row['sha256'] != spec['hgb_generated_shas'][name]:\n"
                "            failures.append('generated-overlay-sha-differs:'+name)\n"
                "    for name, row in modules.items():\n")
    text = once(text, "source_modules=modules,", "source_modules=modules,hgb_source_modules=hgb,hgb_generated_modules=mounted,")
    text = once(text, "    dump(out/'input.json',spec)\n",
                "    spec['hgb_source_shas'] = {n:sha(bundle/'e3_builder'/(n+'.py')) for n in HGB_MODULES}\n"
                "    spec['hgb_generated_shas'] = {n:sha(bundle/'native30_overlay/e3'/(n+'.py')) for n in HGB_MODULES}\n"
                "    sys.path.insert(0,str(bundle/'native35_tools'))\n"
                "    from native37_robust_selfrun import overlay_mounts as _mounts\n"
                "    spec['hgb_generated_paths'] = {n:_mounts(bundle/'native30_overlay')[bundle/'native30_overlay'/'e3']+'/'+n+'.py' for n in HGB_MODULES}\n"
                "    dump(out/'input.json',spec)\n")
    text = once(text, "    container = 'n3j2-frozen-cpu-'+manifest[:12]\n",
                "    suffix = os.environ.get('HGB_FROZEN_CPU_SUFFIX','')\n"
                "    assert re.fullmatch('(-[a-z0-9]{1,8})?',suffix),'container suffix'\n"
                "    container = 'q2024p-j2-hgb-frozen-cpu-'+manifest[:12]+suffix\n")
