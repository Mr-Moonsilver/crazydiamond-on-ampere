#!/usr/bin/env python3
"""Compose the exploratory q2024p-j2 host-gap batch packets (off / on) from the measured j2 bundle.

Parent: the sealed q2024p-j2 bundle f63cff5d1e19 (the measured j2-v1b runs used it unchanged). This packet changes, on
top of those bytes and nothing else:
  * the reviewed host-gap batch source delta (git diff BASE_COMMIT..commit over harness/ and patches/s5_engine/),
    each modified file first proved byte-identical to the parent bundle's copy;
  * bundle n3j2_box.py: one marked observational line keeping the engine's small_piece_batch status block on the arm
    status rows (no key when the flag is 0);
  * the queue triple under the new name, its settings carrying FLASH_S5_SMALL_PIECE_BATCH=0 (off) or =1 (on) and its
    declaration/draft asserting it; the overlay is regenerated by the frozen generator with exactly one new file,
    e3/small_piece_batch.py, and only the declared runtime files moved;
  * the owner runner, frozen CPU tool and queue adapter under the new name, binding the host-gap modules as well.
No box command, GPU, VM, deletion or push.
"""
