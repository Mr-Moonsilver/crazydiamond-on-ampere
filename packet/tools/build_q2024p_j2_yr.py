#!/usr/bin/env python3
"""Compose the exploratory q2024p-j2 yield-rule packets (y1 / y12) from the measured j2 bundle.

This is the yrs tool (tools/build_q2024p_j2_yrs.py, itself the host-gap batch tool) reused unchanged in method, with this
packet's names and inventory. Parent: the same sealed q2024p-j2 bundle f63cff5d1e19. On top of those bytes the packet
changes:
  * the source delta (git diff BASE_COMMIT..commit over harness/ and patches/s5_engine/): the host-gap batch, the yield
    re-entry diagnostic/settle and the yield rules (engine_driver.py, scheduler_hooks.py, native_auto_arm.py), each
    modified file first proved byte-identical to the parent bundle's copy;
  * bundle n3j2_box.py: the hgb tool's one observational line, as in hgb/yrs. The Y1/Y2 status blocks need no harness line:
    they are inside native_admission.queue_policy, which n3j2_box.status_row already copies whole;
  * the queue triple under the new name, its settings carrying FLASH_S5_SMALL_PIECE_BATCH=0,
    FLASH_S5_YIELD_REENTRY_SETTLE=0, FLASH_S5_YIELD_NO_APPEND_OWNER and FLASH_S5_YIELD_WINDOW (y1: 1/0, y12: 1/1) and its
    declaration/draft asserting all four; the overlay regenerated by the frozen generator with one new file
    (e3/small_piece_batch.py) and only the declared runtime files moved (the hgb modules, e3/native_auto_arm.py,
    e3/engine_driver.py and e3/scheduler_hooks.py);
  * the owner runner, frozen CPU tool and queue adapter under the new name, binding those modules.
The yr-off arm is the existing yrs-off packet (no rebuild): with both rule flags unset the rule code is never entered.
The re-entry diagnostic is always on: every arm carries it. No box command, GPU, VM, deletion or push.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location('build_q2024p_j2_yrs', ROOT / 'tools/build_q2024p_j2_yrs.py')
yrs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(yrs)
hgb = yrs.hgb

PARENT_NAME, PARENT, BASE_COMMIT = hgb.PARENT_NAME, hgb.PARENT, hgb.BASE_COMMIT
VARIANTS = {'y1': dict(small_piece_batch='0', yield_reentry_settle='0', no_append_owner='1', yield_window='0'),
            'y12': dict(small_piece_batch='0', yield_reentry_settle='0', no_append_owner='1', yield_window='1')}
Y1_ENV, Y2_ENV = 'FLASH_S5_YIELD_NO_APPEND_OWNER', 'FLASH_S5_YIELD_WINDOW'
BOUND_MODULES = yrs.BOUND_MODULES + ('engine_driver', 'scheduler_hooks')
ENGINE_MOVED = {'e3/' + n + '.py' for n in BOUND_MODULES}
SUITES = yrs.SUITES + ('test_yield_no_append_owner', 'test_yield_window', 'test_q2024p_j2_yr_reader')
TOOLS = yrs.TOOLS + ('tools/q2024p_j2_yr_reader.py', 'tools/build_q2024p_j2_yr.py', 'tools/q2024p_j2_yr_finish.py')
YR_CONTAINER = "'q2024p-j2-yr-frozen-cpu-'"
SETTLE_SETTING = '%s=0 ' % yrs.YRS_ENV
SETTLE_ASSERT = "assert env.get('%s') == '0', 'yield re-entry settle setting differs'\n" % yrs.YRS_ENV


def name_of(variant):
    assert variant in VARIANTS, variant
    return PARENT_NAME + '-yr-' + variant


def queues(variant):
    """The yrs triple (batch 0, settle 0) under the new name; the two rule settings and their four assertions are added."""
    values = VARIANTS[variant]
    result = {}
    for rel, text in yrs.queues(variant).items():
        if rel.endswith('_settings.sh'):
            text = hgb.once(text, SETTLE_SETTING, SETTLE_SETTING + '%s=%s %s=%s ' % (
                Y1_ENV, values['no_append_owner'], Y2_ENV, values['yield_window']))
        else:
            text = hgb.once(text, SETTLE_ASSERT, SETTLE_ASSERT
                            + "assert env.get('%s') == '%s', 'yield rule Y1 setting differs'\n" % (Y1_ENV, values['no_append_owner'])
                            + "assert env.get('%s') == '%s', 'yield rule Y2 setting differs'\n" % (Y2_ENV, values['yield_window']))
        result[rel] = text
    return result


def bind():
    """Point the yrs (and through it the hgb) helpers at this packet's names and inventory."""
    yrs.VARIANTS = VARIANTS
    yrs.name_of = name_of
    yrs.BOUND_MODULES = BOUND_MODULES
    yrs.ENGINE_MOVED = ENGINE_MOVED
    yrs.SUITES = SUITES
    yrs.TOOLS = TOOLS
    yrs.YRS_CONTAINER = YR_CONTAINER
    yrs.bind()


def copy_delta(b, commit, bundle):
    copied = yrs.copy_delta(b, commit, bundle)
    for name in ('patches/s5_engine/engine_driver.py', 'patches/s5_engine/scheduler_hooks.py',
                 'harness/test_yield_no_append_owner.py', 'harness/test_yield_window.py'):
        assert name in copied, name
    return copied


def prepare(commit, variant, out):
    bind()
    b = hgb.helper()
    name = name_of(variant)
    commit = b.git(ROOT, 'rev-parse', commit + '^{commit}').decode().strip()
    assert len(commit) == 40
    assert not out.exists() and not out.is_symlink(), 'fresh output required'
    out.mkdir(parents=True)
    bundle = out / (name + '-bundle-pending')
    shutil.copytree(PARENT, bundle)
    for p in (bundle, *bundle.rglob('*')):
        p.chmod(0o755 if p.is_dir() else 0o644)
    copied = copy_delta(b, commit, bundle)
    box = bundle / 'n3j2_box.py'
    box.write_text(hgb.once(hgb.once(box.read_text(), hgb.BOX_IMPORT, hgb.BOX_IMPORT_NEW), hgb.BOX_ROW, hgb.BOX_ROW_NEW))
    for rel, text in queues(variant).items():
        (bundle / rel).write_text(text)
        subprocess.run(['bash', '-n', str(bundle / rel)], check=True)
    proof = hgb.regenerate(b, bundle, out)
    yrs.frozen_cpu_tool(bundle)
    hgb.queue_adapter(bundle, variant)
    for p in bundle.rglob('*.py'):
        compile(p.read_bytes(), str(p), 'exec')
    manifest = b.manifest(bundle)
    final = out / (name + '-bundle-' + manifest[:12])
    bundle.rename(final)
    runner = out / (name + '-owner-run-' + manifest[:12] + '.py')
    runner.write_text(hgb.runner_text(b, final, manifest, proof, commit, variant))
    compile(runner.read_bytes(), str(runner), 'exec')
    for p in (final, *final.rglob('*')):
        p.chmod(0o555 if p.is_dir() else 0o444)
    runner.chmod(0o444)
    values = VARIANTS[variant]
    record = dict(proof, schema='q2024p-j2-yr-build/1', name=name, variant=variant,
                  small_piece_batch=values['small_piece_batch'], yield_reentry_settle=values['yield_reentry_settle'],
                  no_append_owner=values['no_append_owner'], yield_window=values['yield_window'], diagnostic='always-on',
                  source_commit=commit, base_commit=BASE_COMMIT,
                  bundle=str(final), manifest=manifest, runner=str(runner), runner_sha256=b.sha(runner),
                  runner_size=runner.stat().st_size, held=True, hardware_qualified=False, exploratory=True,
                  parent_manifest=hgb.PARENT_SHA, parent_runner_sha256=hgb.PARENT_RUNNER_SHA,
                  parent_overlay=hgb.PARENT_OVERLAY, source_changes=copied, cpu_suites=SUITES,
                  hgb_modules=BOUND_MODULES, box_action=False, gpu_action=False)
    b.dump(out / 'build.json', record)
    return record


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source-commit', required=True)
    parser.add_argument('--variant', choices=sorted(VARIANTS), required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.source_commit, args.variant, args.out.resolve())
    print(json.dumps({k: v for k, v in result.items() if k != 'source_changes'}, sort_keys=True))
