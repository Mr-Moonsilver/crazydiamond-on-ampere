#!/usr/bin/env python3
"""Compose the exploratory q2024p-j2 ingress packet (ing-on) from the measured j2 bundle.

This is the yr tool (tools/build_q2024p_j2_yr.py, through it the yrs and host-gap batch tools) reused unchanged in
method, with this packet's names and inventory. Parent: the same sealed q2024p-j2 bundle f63cff5d1e19. On top of those
bytes the packet changes:
  * the source delta (git diff BASE_COMMIT..commit over harness/ and patches/s5_engine/): the host-gap batch, the yield
    re-entry diagnostic/settle, the yield rules and the ingress splice + prefix counter (ingress_incremental.py new;
    probe_control.py, executor_hooks.py, engine_driver.py, make_s5_overlap.py, decode_probe.py), each modified file
    first proved byte-identical to the parent bundle's copy;
  * bundle n3j2_box.py: the hgb tool's one observational line, as in hgb/yrs/yr. The ingress blocks need no harness
    line: both sit inside native_admission, which n3j2_box.status_row already copies whole;
  * the queue triple under the new name, its settings carrying FLASH_S5_SMALL_PIECE_BATCH=0,
    FLASH_S5_YIELD_REENTRY_SETTLE=0, FLASH_S5_YIELD_NO_APPEND_OWNER=0, FLASH_S5_YIELD_WINDOW=0 and
    FLASH_S5_INGRESS_INCREMENTAL=1, its declaration/draft asserting all five; the overlay regenerated by the frozen
    generator with two new files (e3/small_piece_batch.py, e3/ingress_incremental.py) and only the declared runtime
    files moved;
  * the owner runner, frozen CPU tool and queue adapter under the new name, binding those modules.
The off arm is the existing yrs-off packet (no rebuild): its engine has neither the splice nor the counter, and every
other setting equals ing-on's. No box command, GPU, VM, deletion or push.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location('build_q2024p_j2_yr', ROOT / 'tools/build_q2024p_j2_yr.py')
yr = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(yr)
yrs, hgb = yr.yrs, yr.hgb

PARENT_NAME, PARENT, BASE_COMMIT = hgb.PARENT_NAME, hgb.PARENT, hgb.BASE_COMMIT
VARIANTS = {'on': dict(small_piece_batch='0', yield_reentry_settle='0', no_append_owner='0', yield_window='0',
                       ingress_incremental='1')}
ING_ENV = 'FLASH_S5_INGRESS_INCREMENTAL'
BOUND_MODULES = yr.BOUND_MODULES + ('probe_control', 'ingress_incremental')
ENGINE_MOVED = {'e3/' + n + '.py' for n in BOUND_MODULES}
NEW_OVERLAY_FILES = set(hgb.NEW_OVERLAY_FILES) | {'e3/ingress_incremental.py'}
SUITES = yr.SUITES + ('test_ingress_incremental', 'test_ingress_incremental_hf', 'test_q2024p_j2_ing_reader')
TOOLS = yr.TOOLS + ('tools/q2024p_j2_ing_reader.py', 'tools/build_q2024p_j2_ing.py', 'tools/q2024p_j2_ing_finish.py')
ING_CONTAINER = "'q2024p-j2-ing-frozen-cpu-'"
Y2_SETTING = '%s=0 ' % yr.Y2_ENV
Y2_ASSERT = "assert env.get('%s') == '0', 'yield rule Y2 setting differs'\n" % yr.Y2_ENV


def name_of(variant):
    assert variant in VARIANTS, variant
    return PARENT_NAME + '-ing-' + variant


def queues(variant):
    """The yr triple (batch, settle, Y1, Y2 all 0) under the new name; the ingress setting and its assertions added."""
    value = VARIANTS[variant]['ingress_incremental']
    result = {}
    for rel, text in yr_queues(variant).items():
        if rel.endswith('_settings.sh'):
            text = hgb.once(text, Y2_SETTING, Y2_SETTING + '%s=%s ' % (ING_ENV, value))
        else:
            text = hgb.once(text, Y2_ASSERT, Y2_ASSERT + "assert env.get('%s') == '%s', 'ingress setting differs'\n"
                            % (ING_ENV, value))
        result[rel] = text
    return result


yr_queues = yr.queues


def bind():
    """Point the yr (and through it the yrs and hgb) helpers at this packet's names and inventory."""
    yr.VARIANTS = VARIANTS
    yr.name_of = name_of
    yr.BOUND_MODULES = BOUND_MODULES
    yr.ENGINE_MOVED = ENGINE_MOVED
    yr.SUITES = SUITES
    yr.TOOLS = TOOLS
    yr.YR_CONTAINER = ING_CONTAINER
    yr.queues = queues
    yr.bind()
    hgb.NEW_OVERLAY_FILES = NEW_OVERLAY_FILES


def copy_delta(b, commit, bundle):
    copied = yr.copy_delta(b, commit, bundle)
    for name in ('patches/s5_engine/ingress_incremental.py', 'patches/s5_engine/probe_control.py',
                 'patches/s5_engine/executor_hooks.py', 'patches/s5_engine/engine_driver.py',
                 'harness/test_ingress_incremental.py', 'harness/test_ingress_incremental_hf.py',
                 'harness/test_q2024p_j2_ing_reader.py'):
        assert name in copied, name
    return copied



def prepare(commit, variant, out):
    """yr.prepare's steps in its order, with this packet's queues, delta check and record."""
    bind()
    b = hgb.helper()
    name = name_of(variant)
    commit = b.git(ROOT, 'rev-parse', commit + '^{commit}').decode().strip()
    assert len(commit) == 40
    assert not out.exists() and not out.is_symlink(), 'fresh output required'
    out.mkdir(parents=True)
    bundle = out / (name + '-bundle-pending')
    shutil.copytree(PARENT, bundle)
    for p in (bundle, *bundle.rglob('*')):
        p.chmod(0o755 if p.is_dir() else 0o644)
    copied = copy_delta(b, commit, bundle)
    box = bundle / 'n3j2_box.py'
    box.write_text(hgb.once(hgb.once(box.read_text(), hgb.BOX_IMPORT, hgb.BOX_IMPORT_NEW), hgb.BOX_ROW, hgb.BOX_ROW_NEW))
    for rel, text in queues(variant).items():
        (bundle / rel).write_text(text)
        subprocess.run(['bash', '-n', str(bundle / rel)], check=True)
    proof = hgb.regenerate(b, bundle, out)
    assert set(NEW_OVERLAY_FILES) <= set(proof['overlay_changed']), 'new overlay files not in the regenerated overlay'
    yrs.frozen_cpu_tool(bundle)
    hgb.queue_adapter(bundle, variant)
    for p in bundle.rglob('*.py'):
        compile(p.read_bytes(), str(p), 'exec')
    manifest = b.manifest(bundle)
    final = out / (name + '-bundle-' + manifest[:12])
    bundle.rename(final)
    runner = out / (name + '-owner-run-' + manifest[:12] + '.py')
    runner.write_text(hgb.runner_text(b, final, manifest, proof, commit, variant))
    compile(runner.read_bytes(), str(runner), 'exec')
    for p in (final, *final.rglob('*')):
        p.chmod(0o555 if p.is_dir() else 0o444)
    runner.chmod(0o444)
    values = VARIANTS[variant]
    record = dict(proof, schema='q2024p-j2-ing-build/1', name=name, variant=variant,
                  small_piece_batch=values['small_piece_batch'], yield_reentry_settle=values['yield_reentry_settle'],
                  no_append_owner=values['no_append_owner'], yield_window=values['yield_window'],
                  ingress_incremental=values['ingress_incremental'], diagnostic='always-on',
                  prefix_counter='always-on in engine arms (log-only)', new_overlay_files=sorted(NEW_OVERLAY_FILES),
                  source_commit=commit, base_commit=BASE_COMMIT,
                  bundle=str(final), manifest=manifest, runner=str(runner), runner_sha256=b.sha(runner),
                  runner_size=runner.stat().st_size, held=True, hardware_qualified=False, exploratory=True,
                  parent_manifest=hgb.PARENT_SHA, parent_runner_sha256=hgb.PARENT_RUNNER_SHA,
                  parent_overlay=hgb.PARENT_OVERLAY, source_changes=copied, cpu_suites=SUITES,
                  hgb_modules=BOUND_MODULES, box_action=False, gpu_action=False)
    b.dump(out / 'build.json', record)
    return record


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source-commit', required=True)
    parser.add_argument('--variant', choices=sorted(VARIANTS), required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.source_commit, args.variant, args.out.resolve())
    print(json.dumps({k: v for k, v in result.items() if k != 'source_changes'}, sort_keys=True))
