#!/usr/bin/env python3
"""Compose the exploratory q2024p-j2 yield re-entry settle packets (off / hgb / on) from the measured j2 bundle.

This is the host-gap batch tool (tools/build_q2024p_j2_hgb.py) reused unchanged in method, with this packet's names and
inventory. Parent: the same sealed q2024p-j2 bundle f63cff5d1e19. On top of those bytes the packet changes:
  * the source delta (git diff BASE_COMMIT..commit over harness/ and patches/s5_engine/): the host-gap batch AND the
    yield re-entry diagnostic/settle (native_auto_arm.py), each modified file first proved byte-identical to the parent
    bundle's copy;
  * bundle n3j2_box.py: the hgb tool's one observational line (small_piece_batch block on the arm status rows). The yield
    re-entry block needs no harness line: it is inside append_yield.declines, which e3_compose5_box.status_row already
    copies whole;
  * the queue triple under the new name, its settings carrying FLASH_S5_SMALL_PIECE_BATCH and
    FLASH_S5_YIELD_REENTRY_SETTLE (off: 0/0, hgb: 1/0, on: 1/1) and its declaration/draft asserting both; the overlay regenerated by
    the frozen generator with one new file (e3/small_piece_batch.py) and only the declared runtime files moved
    (the hgb modules and e3/native_auto_arm.py);
  * the owner runner, frozen CPU tool and queue adapter under the new name, binding the hgb modules and native_auto_arm.
The diagnostic (refusal reasons, retries-until-armed histogram, proof-miss log line) is always on: both arms carry it.
No box command, GPU, VM, deletion or push.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location('build_q2024p_j2_hgb', ROOT / 'tools/build_q2024p_j2_hgb.py')
hgb = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(hgb)

PARENT_NAME, PARENT, BASE_COMMIT = hgb.PARENT_NAME, hgb.PARENT, hgb.BASE_COMMIT
VARIANTS = {'off': dict(small_piece_batch='0', yield_reentry_settle='0'),
            'hgb': dict(small_piece_batch='1', yield_reentry_settle='0'),
            'on': dict(small_piece_batch='1', yield_reentry_settle='1')}
YRS_ENV = 'FLASH_S5_YIELD_REENTRY_SETTLE'
BOUND_MODULES = hgb.HGB_MODULES + ('native_auto_arm',)
ENGINE_MOVED = {'e3/' + n + '.py' for n in BOUND_MODULES}
SUITES = hgb.SUITES + ('test_yield_reentry_settle', 'test_q2024p_j2_yrs_reader')
TOOLS = ('tools/q2024p_j2_yrs_reader.py', 'tools/build_q2024p_j2_yrs.py', 'tools/q2024p_j2_yrs_finish.py')
HGB_CONTAINER = "'q2024p-j2-hgb-frozen-cpu-'"
YRS_CONTAINER = "'q2024p-j2-yrs-frozen-cpu-'"


def name_of(variant):
    assert variant in VARIANTS, variant
    return PARENT_NAME + '-yrs-' + variant


def queues(variant):
    """The parent's queue triple under the new name; the two settings and their four assertions are added."""
    name, values = name_of(variant), VARIANTS[variant]
    result = {}
    for suffix in ('.draft.sh', '_declare.sh', '_settings.sh'):
        text = (PARENT / 'runs' / (hgb.under(PARENT_NAME) + suffix)).read_text()
        text = text.replace(hgb.under(PARENT_NAME), hgb.under(name)).replace(PARENT_NAME, name)
        if suffix == '_settings.sh':
            text = hgb.once(text, 'FLASH_S5_NEXT_LAYER_PREFETCH=1 ',
                            'FLASH_S5_NEXT_LAYER_PREFETCH=1 FLASH_S5_SMALL_PIECE_BATCH=%s %s=%s '
                            % (values['small_piece_batch'], YRS_ENV, values['yield_reentry_settle']))
        else:
            anchor = "assert env.get('FLASH_S5_NEXT_LAYER_PREFETCH') == '1', 'prefetch differs'\n"
            text = hgb.once(text, anchor, anchor
                            + "assert env.get('FLASH_S5_SMALL_PIECE_BATCH') == '%s', 'host-gap batch setting differs'\n"
                            % values['small_piece_batch']
                            + "assert env.get('%s') == '%s', 'yield re-entry settle setting differs'\n"
                            % (YRS_ENV, values['yield_reentry_settle']))
        result['runs/' + hgb.under(name) + suffix] = text
    return result


def bind():
    """Point the hgb helpers at this packet's names and inventory (module globals they read at call time)."""
    hgb.name_of = name_of
    hgb.HGB_MODULES = BOUND_MODULES
    hgb.ENGINE_MOVED = ENGINE_MOVED
    hgb.SUITES = SUITES


def copy_delta(b, commit, bundle):
    copied = hgb.copy_delta(b, commit, bundle)
    assert 'patches/s5_engine/native_auto_arm.py' in copied and 'harness/test_yield_reentry_settle.py' in copied
    for tool in TOOLS:
        target = bundle / 'tools' / Path(tool).name
        assert not target.exists(), tool
        target.write_bytes(b.git(ROOT, 'show', commit + ':' + tool))
        copied[tool] = dict(status='A', bundle=target.relative_to(bundle).as_posix(), sha256=b.sha(target))
    return copied


def frozen_cpu_tool(bundle):
    hgb.frozen_cpu_tool(bundle)
    path = bundle / 'tools/n3j2_frozen_cpu.py'
    path.write_text(hgb.once(path.read_text(), HGB_CONTAINER, YRS_CONTAINER))


def prepare(commit, variant, out):
    bind()
    b = hgb.helper()
    name = name_of(variant)
    commit = b.git(ROOT, 'rev-parse', commit + '^{commit}').decode().strip()
    assert len(commit) == 40
    assert not out.exists() and not out.is_symlink(), 'fresh output required'
    out.mkdir(parents=True)
    bundle = out / (name + '-bundle-pending')
    shutil.copytree(PARENT, bundle)
    for p in (bundle, *bundle.rglob('*')):
        p.chmod(0o755 if p.is_dir() else 0o644)
    copied = copy_delta(b, commit, bundle)
    box = bundle / 'n3j2_box.py'
    box.write_text(hgb.once(hgb.once(box.read_text(), hgb.BOX_IMPORT, hgb.BOX_IMPORT_NEW), hgb.BOX_ROW, hgb.BOX_ROW_NEW))
    for rel, text in queues(variant).items():
        (bundle / rel).write_text(text)
        subprocess.run(['bash', '-n', str(bundle / rel)], check=True)
    proof = hgb.regenerate(b, bundle, out)
    frozen_cpu_tool(bundle)
    hgb.queue_adapter(bundle, variant)
    for p in bundle.rglob('*.py'):
        compile(p.read_bytes(), str(p), 'exec')
    manifest = b.manifest(bundle)
    final = out / (name + '-bundle-' + manifest[:12])
    bundle.rename(final)
    runner = out / (name + '-owner-run-' + manifest[:12] + '.py')
    runner.write_text(hgb.runner_text(b, final, manifest, proof, commit, variant))
    compile(runner.read_bytes(), str(runner), 'exec')
    for p in (final, *final.rglob('*')):
        p.chmod(0o555 if p.is_dir() else 0o444)
    runner.chmod(0o444)
    record = dict(proof, schema='q2024p-j2-yrs-build/1', name=name, variant=variant,
                  small_piece_batch=VARIANTS[variant]['small_piece_batch'],
                  yield_reentry_settle=VARIANTS[variant]['yield_reentry_settle'], diagnostic='always-on',
                  source_commit=commit, base_commit=BASE_COMMIT,
                  bundle=str(final), manifest=manifest, runner=str(runner), runner_sha256=b.sha(runner),
                  runner_size=runner.stat().st_size, held=True, hardware_qualified=False, exploratory=True,
                  parent_manifest=hgb.PARENT_SHA, parent_runner_sha256=hgb.PARENT_RUNNER_SHA,
                  parent_overlay=hgb.PARENT_OVERLAY, source_changes=copied, cpu_suites=SUITES,
                  hgb_modules=BOUND_MODULES, box_action=False, gpu_action=False)
    b.dump(out / 'build.json', record)
    return record


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source-commit', required=True)
    parser.add_argument('--variant', choices=sorted(VARIANTS), required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.source_commit, args.variant, args.out.resolve())
    print(json.dumps({k: v for k, v in result.items() if k != 'source_changes'}, sort_keys=True))
