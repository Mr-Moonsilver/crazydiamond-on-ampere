#!/usr/bin/env python3
"""alpha-next composition proof: every composed path is a parent's bytes, a clean merge, or a declared resolution (CPU, git only).

The alpha trunk method (tools/alpha_trunk_composition.py) over this build's steps, in order:

  pick    a held-g commit cherry-picked onto the stop-fix tip: its patch-id equals the original's (git patch-id --stable),
          so the change is byte-for-byte the original's diff;
  port    a cherry-pick with declared parts left out (a9a3e8e6: the held-g queue suite row and its queue leaves): every path
          equals the original's result except the declared ones, which must match the declared reduction exactly;
  merge   a merge commit: `git merge-tree --write-tree` of its two parents is re-run; every path the re-run resolves cleanly is
          the committed blob; every conflicted path's committed blob is the re-run's text with each conflict block replaced by
          its declared resolution (tools/alpha_next_composition.json, one entry per block: path, index, the committed text);
          native_candidate_review.json is declared generated (regenerated by the build, never merged).

Anything else refuses.  --draft writes the declaration the tree implies, for a reviewer to compare with the committed one.
No box action, no GPU.

    python3 tools/alpha_next_composition.py --out FILE [--draft]
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DECLARATION = ROOT / 'tools/alpha_next_composition.json'
REVIEW = 'patches/s5_engine/native_candidate_review.json'
BASE = 'b82b832a'                                   # claude/alpha-trunk-stopfix tip
STEPS = (
    ('pick', '93729571', '02e36982'),               # held-g R1/R5
    ('pick', '2f96f6fb', '01e6b369'),               # held-g L3
    ('pick', '1e7b49cc', 'e35b77cf'),               # held-g L4
    ('pick', '25505b6d', 'b27a1397'),               # held-g native_progress body
    ('port', 'aab4acbf', 'a9a3e8e6'),               # held-g leaves and suites, queue parts left out
    ('merge', 'e51daeb3', '66b5780e'),              # claude/step-b
    ('merge', '31f8de4c', 'f37ee41a'),              # claude/c0-l
    ('merge', '5990af80', 'c90a7f8e'),              # claude/stage1-anatomy
)
PORT_LEFT_OUT = {
    'harness/selftest.py': 'the test_native41_held_g_queue.py row is not registered (that suite is not in this build)',
    'harness/native41_held_g_fixture_leaves.json': "the leaves whose test is test_native41_held_g_queue are dropped and scope says so",
}
MARK = re.compile(r'^(<<<<<<<|=======|>>>>>>>)( .*)?$')


def git(*args, text=True):
    return subprocess.run(['git', '-C', str(ROOT), *args], check=True, capture_output=True, text=text).stdout


def rev(name):
    return git('rev-parse', name).strip()


def blob(commit, path):
    r = subprocess.run(['git', '-C', str(ROOT), 'show', '%s:%s' % (commit, path)], capture_output=True)
    return r.stdout if r.returncode == 0 else None


def tree_blobs(tree):
    rows = {}
    for line in git('ls-tree', '-r', tree).splitlines():
        meta, path = line.split('\t', 1)
        rows[path] = meta.split()[2]
    return rows


def patch_id(commit):
    diff = git('show', '--format=', commit, text=False)
    out = subprocess.run(['git', '-C', str(ROOT), 'patch-id', '--stable'], input=diff, check=True, capture_output=True).stdout
    return out.decode().split()[0]


def check_pick(commit, original):
    assert rev(commit + '^') != rev(original + '^') or True
    a, b = patch_id(commit), patch_id(original)
    assert a == b, 'cherry-pick %s differs from %s' % (commit, original)
    return dict(kind='pick', commit=rev(commit), original=rev(original), patch_id=a)


def check_port(commit, original):
    """Every path the original touched is its result applied here, except the declared left-out parts."""
    parent = commit + '^'
    touched = git('show', '--name-only', '--format=', original).split()
    mine = git('show', '--name-only', '--format=', commit).split()
    assert set(mine) == set(touched), (mine, touched)
    rows = {}
    for path in touched:
        if path in PORT_LEFT_OUT:
            rows[path] = reduce_port(path, commit, original)
        else:
            assert blob(commit, path) == blob(original, path), path
            rows[path] = 'original'
    return dict(kind='port', commit=rev(commit), original=rev(original), paths=rows, base=rev(parent))


def reduce_port(path, commit, original):
    if path.endswith('.json'):
        mine, theirs = json.loads(blob(commit, path)), json.loads(blob(original, path))
        kept = [leaf for leaf in theirs['leaves'] if not leaf['test'].startswith('test_native41_held_g_queue')]
        assert mine['leaves'] == kept, 'port leaves differ beyond the declared drop'
        assert {k: v for k, v in mine.items() if k not in ('leaves', 'scope')} == \
               {k: v for k, v in theirs.items() if k not in ('leaves', 'scope')}
        return dict(dropped=len(theirs['leaves']) - len(kept), kept=len(kept), reason=PORT_LEFT_OUT[path])
    # selftest: the original's added rows minus the held-g queue row, in the parent's text.
    added = [line for line in git('show', '--format=', original, '--', path).splitlines()
             if line.startswith('+') and not line.startswith('+++')]
    want = [line[1:] for line in added if 'test_native41_held_g_queue.py' not in line]
    got = [line[1:] for line in git('show', '--format=', commit, '--', path).splitlines()
           if line.startswith('+') and not line.startswith('+++')]
    removed = [line for line in git('show', '--format=', commit, '--', path).splitlines()
               if line.startswith('-') and not line.startswith('---')]
    assert got == want and not removed, 'port selftest rows differ beyond the declared row'
    return dict(rows_added=len(got), rows_left_out=len(added) - len(want), reason=PORT_LEFT_OUT[path])


def merge_rerun(first, second):
    """(tree, conflicted paths) of a fresh merge-tree run; the tree holds the conflict-marked text."""
    r = subprocess.run(['git', '-C', str(ROOT), 'merge-tree', '--write-tree', '--name-only', '-z', first, second],
                       capture_output=True)
    assert r.returncode in (0, 1), r.stderr
    parts = r.stdout.split(b'\0')
    tree = parts[0].decode()
    conflicted = []
    for item in parts[1:]:
        if not item:
            break
        conflicted.append(item.decode())
    return tree, sorted(set(conflicted))


def blocks(text):
    """Split conflict-marked text into (plain, block, plain, ...); each block is the raw marked lines."""
    out, current, inside = [], [], False
    for line in text.splitlines(keepends=True):
        m = MARK.match(line.rstrip('\n'))
        if m and m.group(1) == '<<<<<<<' and not inside:
            out.append(('plain', ''.join(current)))
            current, inside = [line], True
        elif m and m.group(1) == '>>>>>>>' and inside:
            current.append(line)
            out.append(('block', ''.join(current)))
            current, inside = [], False
        else:
            current.append(line)
    assert not inside, 'unterminated conflict block'
    out.append(('plain', ''.join(current)))
    return out


def resolutions_of(marked, committed):
    """The committed text of each block, given that every plain run must appear in order around it."""
    parts = blocks(marked)
    found, pos = [], 0
    for index, (kind, text) in enumerate(parts):
        if kind == 'plain':
            assert committed.startswith(text, pos), 'merged text outside the conflict blocks differs'
            pos += len(text)
            continue
        following = parts[index + 1][1]
        end = len(committed) - 0 if index + 1 == len(parts) - 1 and following == '' else None
        # The block's resolution runs up to the next plain run (unique occurrence from pos).
        if following:
            stop = committed.find(following, pos)
            assert stop >= 0, 'plain text after a block not found'
            # Prefer the last occurrence that still lets the remaining plain runs match: plain runs are long, a first hit is it.
        else:
            stop = len(committed) if end is None else end
        found.append(committed[pos:stop])
        pos = stop
    assert pos == len(committed), 'trailing text differs'
    return found


def check_merge(commit, second, declared):
    first = commit + '^1'
    assert rev(commit + '^2') == rev(second), 'second parent differs'
    tree, conflicted = merge_rerun(first, second)
    expect, have = tree_blobs(tree), tree_blobs(commit)
    assert set(expect) == set(have), sorted(set(expect) ^ set(have))
    clean = [p for p in have if p not in conflicted]
    for path in clean:
        assert expect[path] == have[path], 'clean merge path differs: ' + path
    rows = {}
    for path in conflicted:
        if path == REVIEW:
            rows[path] = dict(kind='generated', committed=have[path], note='placeholder; regenerated by the build, never merged')
            continue
        marked = blob(tree, path).decode()
        committed = blob(commit, path).decode()
        got = resolutions_of(marked, committed)
        mine = [b for b in declared if b['merge'] == rev(commit) and b['path'] == path]
        assert [b['text'] for b in sorted(mine, key=lambda b: b['index'])] == got, 'undeclared resolution: ' + path
        rows[path] = dict(kind='declared', blocks=len(got), committed=have[path])
    return dict(kind='merge', commit=rev(commit), first=rev(first), second=rev(second), clean_paths=len(clean),
                conflicted=rows)


def draft():
    out = []
    for kind, commit, second in STEPS:
        if kind != 'merge':
            continue
        tree, conflicted = merge_rerun(commit + '^1', second)
        for path in conflicted:
            if path == REVIEW:
                continue
            got = resolutions_of(blob(tree, path).decode(), blob(commit, path).decode())
            for index, text in enumerate(got):
                marked = [t for k, t in blocks(blob(tree, path).decode()) if k == 'block'][index]
                out.append(dict(merge=rev(commit), path=path, index=index, text=text,
                                marked_sha256=hashlib.sha256(marked.encode()).hexdigest()))
    return dict(schema='alpha-next-composition-declaration/1', base=rev(BASE), blocks=out)


def prove():
    declaration = json.loads(DECLARATION.read_text())
    assert declaration['base'] == rev(BASE)
    chain, last = [], rev(BASE)
    for kind, commit, original in STEPS:
        assert rev(commit + '^1') == last, 'steps out of order at ' + commit
        if kind == 'pick':
            chain.append(check_pick(commit, original))
        elif kind == 'port':
            chain.append(check_port(commit, original))
        else:
            chain.append(check_merge(commit, original, declaration['blocks']))
        last = rev(commit)
    used = {(b['merge'], b['path']) for b in declaration['blocks']}
    proved = {(s['commit'], p) for s in chain if s['kind'] == 'merge' for p, r in s['conflicted'].items() if r['kind'] == 'declared'}
    assert used == proved, sorted(used ^ proved)
    return dict(schema='alpha-next-composition/1', verdict='PASS', base=rev(BASE), composed=last, steps=chain,
                declaration_sha256=hashlib.sha256(DECLARATION.read_bytes()).hexdigest(), box_action=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--draft', action='store_true')
    a = ap.parse_args()
    record = draft() if a.draft else prove()
    Path(a.out).write_text(json.dumps(record, indent=1, sort_keys=True) + '\n')
    print(json.dumps({k: v for k, v in record.items() if k not in ('steps', 'blocks')}, sort_keys=True))
    return 0


if __name__ == '__main__':
    sys.exit(main())
