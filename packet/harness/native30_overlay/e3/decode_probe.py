def validate_transition_acks(command, replies, expected_ranks):
    """Owner's collective boundary: no next dispatch on partial/mixed ACKs.

    Run the ordinary ordered collective RPC, then this check, before resuming
    admission. This validates replies, not a GPU graph-node containment claim.
    """
    if type(command) is not dict or command.get('action') != 'transition':
        raise DecodeProbeError('transition command required')
    ranks = tuple(expected_ranks)
    if not ranks or any(type(r) is not int or r < 0 for r in ranks) or len(set(ranks)) != len(ranks):
        raise DecodeProbeError('unique expected ranks required')
    if type(replies) not in (list, tuple) or len(replies) != len(ranks):
        raise DecodeProbeError('incomplete transition ACK coverage; interval invalid')
    target = 'split' if command['target'] == 'decode-split' else command['target']
    seen = set()
    for ack in replies:
        if type(ack) is not dict or type(ack.get('rank')) is not int:
            raise DecodeProbeError('invalid transition ACK')
        rank = ack['rank']
        if rank in seen or rank not in ranks:
            raise DecodeProbeError('duplicate or foreign transition rank')
        seen.add(rank)
        if (any(type(ack.get(k)) is not int for k in ('route_generation', 'storage_epoch', 'engine_epoch'))
                or ack.get('ack') != 'flash_s5_transition' or ack.get('mode') != 'decode-only-probe'
                or ack.get('route') != target or ack.get('route_generation') != command['route_generation']
                or ack.get('storage_epoch') != command['storage_epoch']
                or ack.get('engine_epoch') != command['engine_epoch']
                or type(ack.get('drained_streams')) is not int or ack['drained_streams'] < 1):
            raise DecodeProbeError('transition ACK identity/drain differs; interval invalid')
    return tuple(sorted(seen))
