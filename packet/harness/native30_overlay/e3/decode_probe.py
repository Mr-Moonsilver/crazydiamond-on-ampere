"""E3 decode-only diagnostic probe (offline runtime contract).

A separately declared diagnostic mode for the first split/decode measurement.
With ``FLASH_S5_DECODE_ONLY_PROBE=1``, ``FLASH_S5_OVERLAP=0`` and an explicit
``FLASH_S5_DECODE_SMS`` the worker constructs only three things beyond stock:

* the green split (``worker_hooks.after_runner_init``),
* the split decode graph bank in its own measured graph pool
  (``split_bank`` + :class:`graph_router.DecodeProbeRouter`),
* the drained :class:`split_bank.RouteController`.

No prefill lane, lane dispatcher, admission, async reply collector, source
lease, prefill communicator, PLE scratch or lane forward is built.  There is no
prefill transaction and no operation ticket: the typed
:class:`graph_router.NoPrefillRoute` guard replaces the anchor transaction, and
only exact descriptors captured in the split bank may replay while the split
route is active.  Any other dispatch invalidates the measured interval and
fails closed -- it is never replayed on the full GPU.

Evidence boundary: CPU fakes prove construction/counters/transition and shutdown
order only.  Measured pool bytes are the free-memory delta around capture;
nothing here establishes SM containment, native progress or a performance
result, and the full package stays ``armable: False``.
"""
import hashlib
import os
from dataclasses import dataclass

from e3_types import E3ContractError
from graph_router import (
    DecodeProbeRouter,
    ExecutionDescriptor,
    NoPrefillRoute,
    UnsupportedRoute,
    descriptor_name,
)
from green_context import declared_decode_sms

PROBE_ENV = 'FLASH_S5_DECODE_ONLY_PROBE'
OVERLAP_ENV = 'FLASH_S5_OVERLAP'
DECODE_SMS_ENV = 'FLASH_S5_DECODE_SMS'

# The decode allocation/storage epoch is stable for the process: route
# transitions advance the route generation, never this number.
STORAGE_EPOCH = 1

# Modules whose generated bytes the declaration records and the gate re-checks.
GENERATED_SOURCES = ('graph_hooks', 'graph_router', 'worker_hooks', 'split_bank',
                     'green_context', 'native_startup', 's5_startup', 'decode_probe')

# Test ids that the declaration must name; the new suite verifies they exist.
REQUIRED_TESTS = (
    'FlagTests.test_both_flags_refused_before_allocation',
    'GateTests.test_require_decode_probe_ready_requires_complete_evidence',
    'RouteGuardTests.test_no_prefill_guard_and_captured_descriptor_routing',
    'RouteGuardTests.test_unsupported_descriptor_invalidates_without_fallback',
    'BankWiringTests.test_separate_pool_and_measured_bytes',
    'TransitionTests.test_drained_transitions_and_refusal_while_unresolved',
    'TransitionTests.test_failed_transition_quarantines_and_keeps_route',
    'ShutdownTests.test_inventory_helper_sha_and_shutdown_order',
    'BytePathTests.test_default_off_generated_sources_are_probe_free',
)

EVIDENCE_KEYS = ('pins', 'helper_source_sha256', 'generated_source_shas', 'tests')

EXCLUDED = ('prefill lane', 'lane dispatcher', 'chunk admission',
            'async reply collector', 'source leases', 'prefill communicators',
            'PLE scratch', 'lane forward')


class DecodeProbeError(E3ContractError):
    """A decode-probe setting, evidence or route violates the diagnostic contract."""


class DecodeProbeNotReady(DecodeProbeError):
    """The declaration/gate evidence is incomplete or does not match this runtime."""


class DecodeProbeInvalidated(DecodeProbeError):
    """An unsupported dispatch ended the measured interval; nothing may fall back."""


class DecodeProbeQuarantined(DecodeProbeError):
    """A failed transition or teardown stopped further probe transitions."""


# --- flags and evidence -----------------------------------------------------

def _flag(env, name):
    value = env.get(name, '0')
    if value not in ('0', '1'):
        raise DecodeProbeError('invalid boolean setting: ' + name)
    return value == '1'


@dataclass(frozen=True)
class DecodeProbeSettings:
    """Declared probe settings; there is no default SM count."""
    decode_sms: int
    storage_epoch: int = STORAGE_EPOCH

    def __post_init__(self):
        if type(self.decode_sms) is not int or self.decode_sms < 1:
            raise DecodeProbeError('decode probe SM count must be a positive int')
        if self.storage_epoch != STORAGE_EPOCH:
            raise DecodeProbeError('decode probe storage epoch is the stable declared epoch')


def mode_settings(env=None):
    """Validate the probe/overlap flags before any allocation.

    Returns :class:`DecodeProbeSettings` in probe mode and ``None`` when the
    probe flag is off (the normal overlap path keeps its own gate).  Both flags
    set, or a probe without an explicit SM declaration, refuse here.
    """
    env = os.environ if env is None else env
    probe = _flag(env, PROBE_ENV)
    overlap = _flag(env, OVERLAP_ENV)
    if probe and overlap:
        raise DecodeProbeError(f'{PROBE_ENV}=1 requires {OVERLAP_ENV}=0')
    if not probe:
        return None
    return DecodeProbeSettings(declared_decode_sms(env))


def _sha_file(path):
    with open(path, 'rb') as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def _is_digest(value):
    return (type(value) is str and len(value) == 64
            and all(c in '0123456789abcdef' for c in value))


def _module_dir():
    return os.path.dirname(os.path.abspath(__file__))


def declared_evidence():
    """Evidence derived from this runtime's pinned transforms and bytes."""
    from graph_hooks import PINNED_SHA256
    from worker_hooks import PINS as WORKER_PINS

    pins = dict(WORKER_PINS)
    pins['v1/worker/gpu/model_runner.py'] = PINNED_SHA256
    shas = {}
    for name in GENERATED_SOURCES:
        path = os.path.join(_module_dir(), name + '.py')
        if not os.path.isfile(path):
            raise DecodeProbeNotReady('generated source is missing: ' + name)
        shas[name] = _sha_file(path)
    return {
        'pins': pins,
        'helper_source_sha256': _helper_sha(),
        'generated_source_shas': shas,
        'tests': REQUIRED_TESTS,
    }


def _helper_sha():
    from green_context import helper_source_sha256

    return helper_source_sha256()


def require_decode_probe_ready(evidence=None):
    """Gate the diagnostic mode on complete, matching evidence.

    This is deliberately separate from ``s5_startup.require_native_ready()``,
    which keeps refusing the full package unchanged.  No environment bypass:
    a caller that supplies incomplete or stale evidence is refused.
    """
    if evidence is None:
        evidence = declared_evidence()
    if not isinstance(evidence, dict):
        raise DecodeProbeNotReady('decode probe evidence must be a mapping')
    missing = [key for key in EVIDENCE_KEYS if key not in evidence]
    if missing:
        raise DecodeProbeNotReady('decode probe evidence lacks ' + ', '.join(missing))
    pins = evidence['pins']
    if type(pins) is not dict or not pins:
        raise DecodeProbeNotReady('decode probe evidence needs transform pins')
    for path, digest in pins.items():
        if not isinstance(path, str) or not path or not _is_digest(digest):
            raise DecodeProbeNotReady('decode probe pin is not a 64-hex digest')
    from graph_hooks import PINNED_SHA256 as runner_pin
    from worker_hooks import PINS as worker_pins

    known = dict(worker_pins)
    known['v1/worker/gpu/model_runner.py'] = runner_pin
    for path, digest in worker_pins.items():
        if pins.get(path) != digest:
            raise DecodeProbeNotReady('decode probe pin does not match the known pin: ' + path)
    if pins.get('v1/worker/gpu/model_runner.py') != runner_pin:
        raise DecodeProbeNotReady('decode probe runner pin does not match the known pin')
    unknown = [path for path in pins if path not in known]
    if unknown:
        raise DecodeProbeNotReady('decode probe evidence names no known pin: ' + unknown[0])
    helper = evidence['helper_source_sha256']
    if not _is_digest(helper) or helper != _helper_sha():
        raise DecodeProbeNotReady('decode probe helper source sha does not match')
    shas = evidence['generated_source_shas']
    if type(shas) is not dict or not shas:
        raise DecodeProbeNotReady('decode probe evidence needs generated-source shas')
    for name, digest in shas.items():
        if not isinstance(name, str) or not name or not _is_digest(digest):
            raise DecodeProbeNotReady('decode probe generated sha is not a 64-hex digest')
    for name in GENERATED_SOURCES:
        path = os.path.join(_module_dir(), name + '.py')
        if name not in shas or not os.path.isfile(path) or shas[name] != _sha_file(path):
            raise DecodeProbeNotReady('decode probe generated sha does not match: ' + name)
    tests = evidence['tests']
    if type(tests) not in (tuple, list) or not tests:
        raise DecodeProbeNotReady('decode probe evidence needs test names')
    if any(type(name) is not str or not name for name in tests):
        raise DecodeProbeNotReady('decode probe test name is empty')
    absent = [name for name in REQUIRED_TESTS if name not in tests]
    if absent:
        raise DecodeProbeNotReady('decode probe evidence lacks tests: ' + ', '.join(absent))
    return dict(evidence)


# --- diagnostics ------------------------------------------------------------

@dataclass(frozen=True)
class ProbeEvent:
    """Typed runner-visible event for the diagnostic interval."""
    kind: str
    reason: str
    route_generation: int
    storage_epoch: int

    def as_dict(self):
        return {'kind': self.kind, 'reason': self.reason,
                'route_generation': self.route_generation,
                'storage_epoch': self.storage_epoch}


class DecodeProbe:
    """Runtime state of one worker's decode-only diagnostic mode.

    The first element of ``excluded`` above is the whole point: this object
    never owns a prefill lane, communicator, dispatcher or admission queue.
    """
    def __init__(self, runner, split, bank, backend, controller, router, settings, *,
                 clock=None, torch_module=None):
        from time import monotonic

        if not isinstance(router, DecodeProbeRouter):
            raise DecodeProbeError('decode probe needs its split-only router')
        if not isinstance(settings, DecodeProbeSettings):
            raise DecodeProbeError('decode probe needs validated settings')
        self.runner = runner
        self.split = split
        self.bank = bank
        self.backend = backend
        self.controller = controller
        self.router = router
        self.settings = settings
        self.clock = monotonic if clock is None else clock
        if torch_module is None:
            import torch as torch_module
        self.torch = torch_module
        self.events = []
        self.transitions = []
        self.invalidations = 0
        self.last_invalidation = None
        self.in_flight = 0
        self.interval = 'idle'
        self.interval_index = 0
        self.quarantined = None
        self.shutdown_record = None

    # -- identity ---------------------------------------------------------
    @property
    def route(self):
        return self.controller.route

    @property
    def route_generation(self):
        return self.controller.route_generation

    @property
    def storage_epoch(self):
        return self.settings.storage_epoch

    def _record(self, kind, reason):
        event = ProbeEvent(kind, reason, self.controller.route_generation,
                           self.storage_epoch)
        self.events.append(event)
        return event

    def _require_not_down(self):
        if self.shutdown_record is not None:
            raise DecodeProbeError('decode probe is shut down')
        if self.quarantined is not None:
            raise DecodeProbeQuarantined('decode probe is quarantined: ' + self.quarantined)

    def _require_usable(self):
        self._require_not_down()
        if self.interval == 'invalidated':
            raise DecodeProbeInvalidated(
                'decode probe interval was invalidated: ' + str(self.last_invalidation))

    # -- routing ----------------------------------------------------------
    def _unsupported_reason(self, descriptor):
        """Classify a descriptor that may not run inside the split interval."""
        if descriptor.cg_mode != 'full':
            return 'non_full_graph'
        if descriptor.num_tokens == 0:
            return 'empty_batch'
        if descriptor.uniform_token_count not in (None, 1):
            return 'prefill_or_mixed_batch'
        if descriptor.num_reqs is not None and descriptor.num_reqs > descriptor.num_tokens:
            return 'prefill_or_mixed_batch'
        if descriptor.num_ubatches != 1:
            return 'multi_ubatch'
        return None

    def invalidate(self, reason):
        """End the measured interval; the dispatch that caused it must fail."""
        if type(reason) is not str or not reason:
            raise DecodeProbeError('invalidation needs a reason')
        if self.interval == 'invalidated':
            return self.last_invalidation
        self.interval = 'invalidated'
        self.last_invalidation = reason
        self.invalidations += 1
        self._record('interval_invalidated', reason)
        return reason

    def check_route(self, descriptor, guard=None):
        """Typed route query for the generated dispatch seam.

        ``None`` means the probe is not on the split route (stock behaviour
        before entering the measured interval).  On the split route only exact
        captured decode descriptors pass; anything else invalidates and raises.
        ``guard`` is the typed no-prefill transaction supplied by
        ``graph_hooks._transaction``.
        """
        if type(descriptor) is not ExecutionDescriptor:
            raise DecodeProbeError('decode probe route needs an ExecutionDescriptor')
        if self.controller.route != 'split':
            return None
        self._require_usable()
        if guard is not None and type(guard) is not NoPrefillRoute:
            raise DecodeProbeError('decode probe route needs the typed no-prefill guard')
        reason = self._unsupported_reason(descriptor)
        if reason is not None:
            self.invalidate(reason)
            raise DecodeProbeInvalidated('decode probe refuses ' + reason)
        if guard is None:
            guard = self.router.no_prefill_guard()
        try:
            return self.router.supported_route(guard, descriptor)
        except UnsupportedRoute as exc:
            self.invalidate('unsupported_descriptor')
            raise DecodeProbeInvalidated(
                'decode probe refuses an uncaptured descriptor') from exc

    def replay(self, descriptor):
        """Replay an exact captured descriptor; never fall back to full GPU."""
        if self.controller.route != 'split':
            raise DecodeProbeError('decode probe replay called off the split route')
        self._require_usable()
        reason = self._unsupported_reason(descriptor)
        if reason is not None:
            self.invalidate(reason)
            raise DecodeProbeInvalidated('decode probe refuses ' + reason)
        guard = self.router.no_prefill_guard()
        stream = self.torch.cuda.current_stream(self.runner.device)
        observed_stream = int(getattr(stream, 'cuda_stream', -1))
        self.in_flight += 1
        try:
            return self.router.replay(
                guard, descriptor,
                observed_context=self.split.decode_context_id,
                observed_stream=observed_stream)
        except (UnsupportedRoute, E3ContractError):
            self.invalidate('replay_refused')
            raise
        except BaseException:
            self.invalidate('replay_failed')
            raise
        finally:
            self.in_flight -= 1

    # -- capture, warmup and inventory ------------------------------------
    def capture(self):
        self._require_not_down()
        return self.router.capture_at_startup()

    def warmup(self):
        """Warm every captured graph on the green decode stream, counted apart."""
        self._require_not_down()
        with self.torch.cuda.stream(self.split.decode_stream):
            return self.router.warmup()

    def inventory(self):
        """Startup record: identities and measured bytes only, never guesses."""
        measured = self.bank.measured_bytes
        identity = getattr(self.split.binding, 'identity', None)
        binding_identity = identity() if callable(identity) else {}
        if not isinstance(binding_identity, dict):
            binding_identity = {}
        library_sha = getattr(self.split.binding, 'library_sha256', None)
        if library_sha is None:
            library_sha = binding_identity.get('library_sha256')
        record = {
            'mode': 'decode-only-probe',
            'helper_source_sha256': _helper_sha(),
            'library_sha256': library_sha,
            'binding_identity': binding_identity,
            'split': self.split.describe(),
            'descriptors': [{'label': descriptor_name(d),
                             'cg_mode': d.cg_mode,
                             'num_tokens': d.num_tokens,
                             'num_reqs': d.num_reqs,
                             'uniform_token_count': d.uniform_token_count}
                            for d in self.router.descriptors],
            'descriptors_captured': len(self.router.handles),
            'split_pool_bytes': measured,
            'split_pool_basis': 'measured' if measured is not None else 'uncaptured',
            'split_pool_id': self.router.context.pool_id,
            'split_pool_context_id': self.router.context.context_id,
            'storage_epoch': self.storage_epoch,
            'route': self.controller.route,
            'route_generation': self.controller.route_generation,
            'communicators': 'none',
            'pp_channel_bytes': 0,
            'ple_scratch_bytes': 0,
            'excluded': list(EXCLUDED),
        }
        return record

    def counters(self):
        """Everything the GPU test reads; exposed on the runner as a callable."""
        record = self.router.counters()
        record.update({
            'mode': 'decode-only-probe',
            'route': self.controller.route,
            'route_generation': self.controller.route_generation,
            'storage_epoch': self.storage_epoch,
            'interval': self.interval,
            'interval_index': self.interval_index,
            'interval_invalidations': self.invalidations,
            'invalidation_reasons': [event.reason for event in self.events
                                     if event.kind == 'interval_invalidated'],
            'transition_count': len(self.transitions),
            'transition_latencies_s': [record['seconds'] for record in self.transitions],
            'quarantined': self.quarantined,
        })
        return record

    # -- transitions ------------------------------------------------------
    def transition(self, target):
        """Enter/leave the split route after draining every consumer stream.

        A refusal before switching leaves the route untouched.  An exception
        during the drained switch quarantines the probe: no further
        transitions, the runner is put back on the route it was on, and every
        later dispatch on that route behaves as before.
        """
        if target not in ('split', 'full'):
            raise DecodeProbeError(f'unknown decode probe route {target!r}')
        self._require_not_down()
        if self.in_flight:
            raise DecodeProbeError('no transition while decode work is unresolved')
        if not getattr(self.controller, 'admitting', True):
            raise DecodeProbeError('no transition while another switch is draining')
        if target == self.route:
            raise DecodeProbeError(f'decode probe is already on the {target} route')
        started = self.clock()
        try:
            record = (self.controller.enter_split() if target == 'split'
                      else self.controller.leave_split())
        except BaseException as exc:
            self._fail_transition(target, exc)
            raise
        seconds = self.clock() - started
        self.router.set_route_generation(record.generation)
        self.transitions.append({'source': record.source, 'target': record.target,
                                 'route_generation': record.generation,
                                 'drained_streams': record.drained_streams,
                                 'seconds': seconds})
        if target == 'split':
            self.interval_index += 1
            self.interval = 'active'
            self._record('interval_started', f'interval {self.interval_index}')
        else:
            if self.interval == 'active':
                self._record('interval_ended', 'left split route')
            self.interval = 'ended'
        return record

    def _fail_transition(self, target, exc):
        self.quarantined = f'transition to {target} failed: {type(exc).__name__}'
        self._record('transition_failed', self.quarantined)
        self._restore_route()

    def _restore_route(self):
        """Put the runner back on the route the controller still reports."""
        try:
            controller = self.controller
            if controller.route == 'split':
                stream = self.split.decode_stream
                self.runner.__dict__['main_stream'] = stream
                handler = getattr(self.runner, 'pp_handler', None)
                if handler is not None:
                    handler.main_stream = stream
                self.runner._flash_s5_decode_stream = stream
            else:
                self.runner.__dict__['main_stream'] = controller.full_main_stream
                handler = getattr(self.runner, 'pp_handler', None)
                if handler is not None:
                    handler.main_stream = controller.full_pp_stream
                self.runner._flash_s5_decode_stream = None
        except BaseException:
            self._record('route_restore_failed', self.quarantined or 'unknown')

    # -- teardown ---------------------------------------------------------
    def shutdown(self):
        """Leave split if entered, drain, destroy graphs, close bank, close split."""
        if self.shutdown_record is not None:
            return self.shutdown_record
        order = []
        try:
            if self.controller.route != 'full':
                # Teardown leaves the split even after a quarantine: the
                # controller is the only object that can put the worker back
                # on the full streams, and closing the bank requires it.
                record = self.controller.leave_split()
                self.router.set_route_generation(record.generation)
                self.interval = 'ended'
                self._record('interval_ended', 'left split route for shutdown')
                order.append('leave-split')
            order.append(f'drain:{self.controller.drain()}')
            order.extend(self.router.shutdown())
            from split_bank import shutdown as shutdown_bank

            shutdown_bank(self.runner)
            order.extend(('bank', 'split'))
        except BaseException as exc:
            self.quarantined = f'shutdown failed: {type(exc).__name__}'
            self._record('shutdown_failed', self.quarantined)
            raise
        self.interval = 'ended' if self.interval in ('active', 'invalidated') else 'closed'
        self.shutdown_record = {
            'order': tuple(order),
            'graphs': sum(1 for step in order if step == 'graph'),
            'split_pool_bytes': self.bank.measured_bytes,
            'split_state': self.split.state,
            'route': self.controller.route,
            'route_generation': self.controller.route_generation,
            'storage_epoch': self.storage_epoch,
        }
        return self.shutdown_record


